"""
SoliZer Intelligence Platform - Alerts & Recommendations Router.

Provides endpoints for querying system-generated alerts and
actionable recommendations associated with a plant.

Alerts and recommendations are populated by the analytics / alerting
engines; these endpoints simply expose them from the database.
"""
from typing import List, Optional

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.db.database import get_db
from app.db.models import Alert, Plant, Recommendation
from app.schemas.analytics_schemas import AlertResponse, RecommendationResponse

router = APIRouter()


@router.get(
    "/{plant_id}/alerts",
    response_model=List[AlertResponse],
    summary="List alerts for a plant",
)
def list_alerts(
    plant_id: int,
    severity: Optional[str] = Query(
        None,
        description="Filter by severity level (e.g. 'low', 'medium', 'high', 'critical')",
    ),
    db: Session = Depends(get_db),
):
    """
    Return all alerts associated with the specified plant.

    An optional **severity** query parameter filters the results to only
    alerts matching the given severity level.

    Raises **404** if the plant does not exist.
    """
    plant = db.query(Plant).filter(Plant.id == plant_id).first()
    if not plant:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Plant with id {plant_id} not found.",
        )

    query = db.query(Alert).filter(Alert.plant_id == plant_id)

    if severity is not None:
        query = query.filter(Alert.severity == severity.lower())

    alerts = query.order_by(Alert.created_at.desc()).all()
    return alerts


@router.get(
    "/{plant_id}/recommendations",
    response_model=List[RecommendationResponse],
    summary="List recommendations for a plant",
)
def list_recommendations(plant_id: int, db: Session = Depends(get_db)):
    """
    Return all actionable recommendations for the specified plant.

    Recommendations are generated by the analytics engines and may
    include maintenance suggestions, cleaning schedules, or performance
    improvement tips.

    Raises **404** if the plant does not exist.
    """
    plant = db.query(Plant).filter(Plant.id == plant_id).first()
    if not plant:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Plant with id {plant_id} not found.",
        )

    recommendations = (
        db.query(Recommendation)
        .filter(Recommendation.plant_id == plant_id)
        .order_by(Recommendation.created_at.desc())
        .all()
    )
    return recommendations
